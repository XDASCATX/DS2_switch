#!/usr/bin/env bash
# DS2 port: compiles sdk/src/graphics/shaders/ds2/direct_resolve_fast_32bpp.comp into the four SPIR-V
# headers used by VulkanRenderTargetCache (direct host render target resolve). Needs glslangValidator.
set -euo pipefail
here="$(cd "$(dirname "$0")/../.." && pwd)"
src="$here/sdk/src/graphics/shaders/ds2/direct_resolve_fast_32bpp.comp"
out="$here/sdk/src/graphics/shaders/vulkan_spirv"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
for depth in 0 1; do
  for ms in 0 1; do
    name="ds2_direct_resolve_fast_32bpp_$([ $depth = 1 ] && echo depth || echo color)$([ $ms = 1 ] && echo _ms || true)_cs"
    glslangValidator -V --target-env vulkan1.0 -S comp -DSRC_DEPTH=$depth -DSRC_MS=$ms \
      --vn "$name" -o "$tmp/$name.h" "$src" > /dev/null
    glslangValidator -V --target-env vulkan1.0 -S comp -DSRC_DEPTH=$depth -DSRC_MS=$ms \
      -o "$tmp/$name.spv" "$src" > /dev/null
    spirv-val --target-env vulkan1.0 "$tmp/$name.spv"
    { echo "// Generated by tools/ds2/gen_direct_resolve_shaders.sh from shaders/ds2/direct_resolve_fast_32bpp.comp"
      echo "// (SRC_DEPTH=$depth, SRC_MS=$ms). Do not edit."
      echo "#pragma once"
      sed 's/^const uint32_t/inline constexpr uint32_t/' "$tmp/$name.h"; } > "$out/$name.h"
    echo "$out/$name.h"
  done
done
